/**
 * A remote service, injected into a component.
 *
 *   pnpm start                                            # with the stub
 *   BROKER_URL=http://localhost:8887/ddsr/rest pnpm start # against a broker
 *
 * Three modules, and only one of them was written by hand for this
 * example:
 *
 *   ddsr             publishes the client and the REST flavor
 *   payment.contract GENERATED by `ddsr-codegen --tsm`, mirrors the
 *                    Payment contract into the registry
 *   checkout         @component with @inject(Payment), calls charge()
 *
 * The interesting file is modules/checkout.ts, for what is not in it:
 * no broker, no lookup, no undefined check, no listener. It asks for
 * the contract in its constructor and is not constructed until one is
 * there.
 */

import 'reflect-metadata';
import { ModuleLoader } from '@eclipse-daanse/tsm';
import { pathToFileURL } from 'node:url';
import { Payment } from '@ddsr/stubs/PaymentModule';
import { stub } from './broker-stub';

const entry = (file: string) => pathToFileURL(new URL(file, import.meta.url).pathname).href;

async function main(): Promise<void> {
  const loader = new ModuleLoader();

  loader.register([
    { id: 'ddsr', version: '1.0.0', entry: entry('./modules/ddsr.ts'),
      provides: [{ id: 'ddsr.client' }, { id: 'ddsr.flavor' }] },

    // Generated. Nobody wrote this module; it mirrors the Payment
    // implementations the broker holds, addressed by the contract's
    // fingerprint.
    { id: 'payment.contract', version: '1.0.0',
      entry: import.meta.resolve('@ddsr/stubs/PaymentModule'),
      requiresService: [{ id: 'ddsr.client' }],
      provides: [{ id: String(Payment) }] },

    // The component waits for the contract, and is stopped if it goes.
    { id: 'checkout', version: '1.0.0', entry: entry('./modules/checkout.ts'),
      requiresService: [{ id: String(Payment) }] },
  ]);

  console.log(`starting ${stub ? 'with the built-in broker stub' : 'against a real broker'}\n`);
  await loader.loadAll();

  const registry = loader.getServiceRegistry();
  console.log('\nmodules  :', loader.getManifests()
    .map(m => `${m.id}=${loader.isLoaded(m.id) ? 'active' : 'waiting'}`).join('  '));
  console.log('injected :', registry.countProviders(String(Payment)), `provider(s) of ${String(Payment)}`);

  process.exit(0);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
