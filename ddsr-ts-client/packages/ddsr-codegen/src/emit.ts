import { eClassName, fingerprint, propertyValue, toArray } from '@ddsr/client';
import type {
  Parameter, Property, SecurityRequirement, ServiceException, ServiceInterface, ServiceOperation,
} from '@ddsr/model';
import { identifier, mapEType, mapType } from './type-mapping.js';
import type { MappedType } from './type-mapping.js';

export interface GeneratedFile {
  path: string;
  content: string;
}

const HEADER = `/*
 * Generated by @ddsr/codegen from a DDSR service catalog.
 * DO NOT EDIT - regenerate instead.
 */
`;

/**
 * The consumer's side of a contract: the interface to call, the name to
 * look it up under, and the fingerprint the catalog carried when this
 * was generated.
 *
 * The fingerprint is the reason this is worth generating rather than
 * writing by hand. Passed to find(), the broker returns only
 * implementations whose contract hashes to exactly it — so a provider
 * that has since changed its operations is not silently called with the
 * signature this file believes in. A handwritten stub cannot know that
 * number.
 */
export function emitConsumer(serviceInterface: ServiceInterface): GeneratedFile {
  const name = identifier(serviceInterface.name, 'Service');
  const operations = toArray<ServiceOperation>(serviceInterface.operations);
  const imports = new Set<string>();

  const methods = operations.map(operation => {
    const method = identifier(operation.name, 'operation');
    const returned = slotType(operation.returnValue);
    if (returned.modelImport) imports.add(returned.modelImport);

    const parameters = sortedParameters(operation).map(parameter => {
      const mapped = slotType(parameter);
      if (mapped.modelImport) imports.add(mapped.modelImport);
      const optional = parameter.optional === true ? '?' : '';
      return `${identifier(parameter.name, 'arg')}${optional}: ${mapped.text}`;
    });

    return `${doc(operation.description, '  ', parameterDocs(operation))}  ${method}(${parameters.join(', ')}): Promise<${returned.text === 'void' ? 'void' : returned.text}>;`;
  });

  const sd1 = fingerprint(serviceInterface);
  const body: Array<string | null> = [
    HEADER,
    imports.size > 0 ? `import type { ${[...imports].sort().join(', ')} } from '@ddsr/model';` : null,
    `import { serviceProxy } from '@ddsr/client';`,
    `import type { DdsrConsumer } from '@ddsr/client';`,
    ``,
    docOrNull(serviceInterface.description, ''),
    `export interface ${name} {`,
    methods.join('\n\n'),
    `}`,
    ``,
    `/** The ServiceInterface.name this contract is registered under. */`,
    `export const ${name}InterfaceName = ${quote(serviceInterface.name ?? name)};`,
    ``,
    `/** The version the catalog carried when this file was generated. */`,
    `export const ${name}Version = ${quote(serviceInterface.version ?? '')};`,
    ``,
    `/**`,
    ` * The sd1 fingerprint of the contract above. Pass it to find() and`,
    ` * the broker answers only with implementations whose description`,
    ` * hashes to exactly this - compatibility by identity, so a provider`,
    ` * that changed its operations is not called with these signatures.`,
    ` */`,
    `export const ${name}Fingerprint = ${quote(sd1 ?? '')};`,
    ``,
    `/**`,
    ` * Resolve one, contract-addressed. Returns undefined when the broker`,
    ` * knows no implementation of exactly this contract.`,
    ` *`,
    ` * The proxy is built on the locator the fingerprinted lookup`,
    ` * returned. Going back through getService() would look the service`,
    ` * up a second time and without the fingerprint, so the call could`,
    ` * land on an implementation that does not answer to this contract -`,
    ` * which is the one thing addressing by fingerprint is for.`,
    ` */`,
    `export async function get${name}(`,
    `  consumer: DdsrConsumer,`,
    `  filter?: string`,
    `): Promise<${name} | undefined> {`,
    `  const locator = await consumer.findOne(${name}InterfaceName, filter, ${name}Fingerprint);`,
    `  return locator ? serviceProxy<${name}>(locator) : undefined;`,
    `}`,
    ``,
  ];
  return { path: `src/${name}.ts`, content: render(body) };
}

/**
 * A TSM module that puts the contract into the registry, so a component
 * takes it by injection rather than resolving it.
 *
 * This is the difference between
 *
 *     const payment = await getPayment(client.consumer);
 *     if (!payment) return;              // and now what?
 *
 * and
 *
 *     @component()
 *     class Checkout {
 *       constructor(@inject(Payment) private payments: Payment) {}
 *     }
 *
 * The second never sees an undefined, because a component with an
 * unsatisfied reference does not run. It also stops when the provider
 * goes away and starts again when one returns - the lifecycle the
 * registry already does, applied to a service that happens to be
 * remote.
 *
 * The mirror is fingerprint-addressed: only implementations answering
 * to exactly this contract are registered, so what gets injected has
 * the operations this package declares.
 */
export function emitModule(serviceInterface: ServiceInterface): GeneratedFile {
  const name = identifier(serviceInterface.name, 'Service');
  const body: Array<string | null> = [
    HEADER,
    `import { serviceId } from '@eclipse-daanse/tsm';`,
    `import type { ModuleContext } from '@eclipse-daanse/tsm';`,
    `import { DdsrClientService, mirrorRemoteServices, remoteServiceId } from '@ddsr/tsm';`,
    `import type { RemoteMirror } from '@ddsr/tsm';`,
    `import { ${name}Fingerprint, ${name}InterfaceName } from './${name}.js';`,
    `import type { ${name} as ${name}Contract } from './${name}.js';`,
    ``,
    `/** The id ${serviceInterface.name ?? name} is injected under. */`,
    `export const ${name} = serviceId<${name}Contract>(remoteServiceId(${name}InterfaceName));`,
    ``,
    `let mirror: RemoteMirror | undefined;`,
    ``,
    `/**`,
    ` * Mirrors the implementations the broker holds for this contract.`,
    ` * Needs a published DdsrClient, so declare 'ddsr.client' in this`,
    ` * module's manifest requirements and it waits for one.`,
    ` */`,
    `export async function activate(context: ModuleContext): Promise<void> {`,
    `  const client = context.services.getRequired(DdsrClientService);`,
    `  mirror = await mirrorRemoteServices({`,
    `    registry: context.services,`,
    `    consumer: client.consumer,`,
    `    interfaceName: ${name}InterfaceName,`,
    `    fingerprint: ${name}Fingerprint,`,
    `    id: String(${name}),`,
    `    log: (message) => context.log.info(message),`,
    `  });`,
    `}`,
    ``,
    `export async function deactivate(): Promise<void> {`,
    `  await mirror?.close();`,
    `  mirror = undefined;`,
    `}`,
    ``,
  ];
  return { path: `src/${name}Module.ts`, content: render(body) };
}


/**
 * The provider's side: what an implementation has to offer, and the
 * contract as a model object to publish it with.
 *
 * The second part is what makes this more than a convenience. A
 * provider has to hand the broker a ServiceInterface built feature by
 * feature - the example does it in 154 lines for two operations - and
 * every detail that drifts from the catalog changes the fingerprint,
 * which means consumers stop finding the service. Generated from the
 * catalog, it cannot drift.
 */
export function emitProvider(serviceInterface: ServiceInterface): GeneratedFile {
  const name = identifier(serviceInterface.name, 'Service');
  const operations = toArray<ServiceOperation>(serviceInterface.operations);
  const imports = new Set<string>();

  const methods = operations.map(operation => {
    const method = identifier(operation.name, 'operation');
    const returned = slotType(operation.returnValue);
    if (returned.modelImport) imports.add(returned.modelImport);
    const parameters = sortedParameters(operation).map(parameter => {
      const mapped = slotType(parameter);
      if (mapped.modelImport) imports.add(mapped.modelImport);
      return `${identifier(parameter.name, 'arg')}${parameter.optional === true ? '?' : ''}: ${mapped.text}`;
    });
    const result = returned.text === 'void' ? 'void | Promise<void>' : `${returned.text} | Promise<${returned.text}>`;
    return `${doc(operation.description, '  ', parameterDocs(operation))}  ${method}(${parameters.join(', ')}): ${result};`;
  });

  const needsProxy = operations.some(operation =>
    [operation.returnValue, ...sortedParameters(operation)].some(slot => eTypeUri(slot?.eType) !== undefined));
  const exceptions = toArray<ServiceException>(serviceInterface.exceptions);
  const needsProps = exceptions.some(exception => toArray(exception.properties).length > 0);

  const body: Array<string | null> = [
    HEADER,
    needsProxy ? `import { BasicEClass, URI } from '@emfts/core';` : null,
    needsProxy ? `import type { EClassifier } from '@emfts/core';` : null,
    needsProps ? `import { props } from '@ddsr/client';` : null,
    `import { DDSRFactory } from '@ddsr/model';`,
    `import type { ${[...new Set([...imports, 'ServiceInterface'])].sort().join(', ')} } from '@ddsr/model';`,
    ``,
    docOrNull(serviceInterface.description, '', [`The implementation side of ${serviceInterface.name ?? name}. Every operation`, 'the catalog declares has to be here; a return value may be a', 'promise or not.']),
    `export interface ${name}Implementation {`,
    methods.join('\n\n'),
    `}`,
    ``,
    `/** The operation names, for wiring a transport that dispatches by name. */`,
    `export const ${name}OperationNames = [${operations.map(o => quote(o.name ?? '')).join(', ')}] as const;`,
    ``,
    `/**`,
    ` * The contract as a model object, exactly as the catalog has it.`,
    ` * This is what publish() needs, and what the fingerprint is computed`,
    ` * over - so it is generated rather than typed out.`,
    ` */`,
    `export function build${name}Interface(): ServiceInterface {`,
    `  const factory = DDSRFactory.eINSTANCE;`,
    `  const serviceInterface = factory.createServiceInterface();`,
    ...assign('serviceInterface', 'name', serviceInterface.name),
    ...assign('serviceInterface', 'version', serviceInterface.version),
    ...assign('serviceInterface', 'description', serviceInterface.description),
    ...(serviceInterface.status === 'DEPRECATED' ? [`  serviceInterface.status = 'DEPRECATED';`] : []),
    ...buildSecurity('serviceInterface', serviceInterface.security),
    ...exceptions.flatMap((exception, index) => buildException(exception, index)),
    ...operations.flatMap((operation, index) => buildOperation(operation, index, exceptions)),
    `  return serviceInterface;`,
    `}`,
    ``,
    ...(needsProxy ? [
      `/**`,
      ` * An eType as the broker holds it: a proxy naming the classifier by`,
      ` * URI. The fingerprint reads that URI and nothing else, so the`,
      ` * provider's metamodel need not be loaded to publish the contract.`,
      ` */`,
      `function eTypeProxy(uri: string): EClassifier {`,
      `  const proxy = new BasicEClass();`,
      `  proxy.eSetProxyURI(URI.createURI(uri));`,
      `  return proxy;`,
      `}`,
      ``,
    ] : []),
  ];
  return { path: `src/${name}Provider.ts`, content: render(body) };
}

function buildOperation(operation: ServiceOperation, index: number, exceptions: ServiceException[]): string[] {
  const local = `operation${index}`;
  const lines = [
    ``,
    `  const ${local} = factory.createServiceOperation();`,
    ...assign(local, 'name', operation.name),
    ...assign(local, 'description', operation.description),
    ...buildSecurity(local, operation.security),
  ];
  // Non-containment: an operation names exceptions its interface owns
  for (const raised of toArray<ServiceException>(operation.exceptions)) {
    const owner = exceptions.findIndex(exception => exception.name === raised.name);
    if (owner < 0) {
      throw new Error(`${operation.name} raises ${raised.name}, which its interface does not declare`);
    }
    lines.push(`  ${local}.exceptions.push(exception${owner});`);
  }
  if (operation.returnValue) {
    lines.push(
      ...buildSlot(`${local}Result`, operation.returnValue, 0),
      `  ${local}.returnValue = ${local}Result;`,
    );
  }
  for (const [at, parameter] of sortedParameters(operation).entries()) {
    const parameterLocal = `${local}Parameter${at}`;
    lines.push(
      ...buildSlot(parameterLocal, parameter, at),
      `  ${local}.parameters.push(${parameterLocal});`,
    );
  }
  lines.push(`  serviceInterface.operations.push(${local});`);
  return lines;
}

/** A ServiceException the interface owns, properties included. */
function buildException(exception: ServiceException, index: number): string[] {
  const local = `exception${index}`;
  return [
    ``,
    `  const ${local} = factory.createServiceException();`,
    ...assign(local, 'name', exception.name),
    ...assign(local, 'type', exception.type),
    ...assign(local, 'version', exception.version),
    ...assign(local, 'description', exception.description),
    ...toArray<Property>(exception.properties).map(property => `  ${local}.properties.push(${propertyExpression(property)});`),
    `  serviceInterface.exceptions.push(${local});`,
  ];
}

/** A property as the props builder that makes the same one. */
function propertyExpression(property: Property): string {
  const name = quote(property.name ?? '');
  const value = propertyValue(property);
  switch (eClassName(property)) {
    case 'StringProperty': return `props.string(${name}, ${quote(String(value ?? ''))})`;
    case 'IntProperty': return `props.int(${name}, ${Number(value)})`;
    case 'LongProperty': return `props.long(${name}, ${Number(value)})`;
    case 'ShortProperty': return `props.short(${name}, ${Number(value)})`;
    case 'DoubleProperty': return `props.double(${name}, ${Number(value)})`;
    case 'FloatProperty': return `props.float(${name}, ${Number(value)})`;
    case 'BoolProperty': return `props.bool(${name}, ${value === true})`;
    case 'StringListProperty': return `props.stringList(${name}, [${(value as string[]).map(quote).join(', ')}])`;
    default:
      throw new Error(`cannot reproduce a ${eClassName(property)} property (${property.name})`);
  }
}

/** A security requirement, on the interface or on one operation - both are sd1. */
function buildSecurity(target: string, requirement: SecurityRequirement | undefined): string[] {
  if (!requirement) return [];
  const local = `${target}Security`;
  return [
    `  const ${local} = factory.createSecurityRequirement();`,
    ...(requirement.authenticated === true ? [`  ${local}.authenticated = true;`] : []),
    ...toArray<string>(requirement.scopes).map(scope => `  ${local}.scopes.push(${quote(scope)});`),
    `  ${target}.security = ${local};`,
  ];
}

/**
 * One Parameter, as a parameter or as the return slot (#41). Bounds are
 * written only where they differ from the model default of 1, the eType
 * as the proxy the catalog carried.
 */
function buildSlot(local: string, slot: Parameter, at: number): string[] {
  const lower = boundOf(slot.lowerBound);
  const upper = boundOf(slot.upperBound);
  const uri = eTypeUri(slot.eType);
  return [
    `  const ${local} = factory.createParameter();`,
    ...assign(local, 'name', slot.name),
    ...assign(local, 'type', slot.type),
    ...assign(local, 'description', slot.description),
    ...(at > 0 ? [`  ${local}.index = ${at};`] : []),
    ...(slot.optional === true ? [`  ${local}.optional = true;`] : []),
    ...assign(local, 'defaultValue', slot.defaultValue),
    ...(lower !== 1 ? [`  ${local}.lowerBound = ${lower};`] : []),
    ...(upper !== 1 ? [`  ${local}.upperBound = ${upper};`] : []),
    ...(uri !== undefined ? [`  ${local}.eType = eTypeProxy(${quote(uri)});`] : []),
  ];
}

/**
 * The TypeScript type of a slot - a parameter, or the return value. The
 * eType wins where it is set, read from the proxy URI as the fingerprint
 * does, since the provider's metamodel is normally not on hand; only
 * without one does the `type` string decide. That precedence is
 * java-types.mtl's, and the two must not differ. A multi-valued slot is
 * an array, and no slot at all is a void return.
 */
function slotType(slot: Parameter | undefined): MappedType {
  if (!slot) return { text: 'void' };
  const uri = eTypeUri(slot.eType);
  const mapped = uri !== undefined ? mapEType(uri) : mapType(slot.type);
  const upper = boundOf(slot.upperBound);
  const many = upper === -1 || upper > 1;
  return many && !mapped.text.endsWith('[]') ? { ...mapped, text: `${mapped.text}[]` } : mapped;
}

/** A bound as a number; absent means the model default of 1. */
function boundOf(value: unknown): number {
  if (value === undefined || value === null || value === '') return 1;
  const parsed = Number(value);
  return Number.isFinite(parsed) ? parsed : 1;
}

/** `<nsURI>#//<Name>` for an eType, proxy or resolved - as sd1 renders it. */
function eTypeUri(eType: unknown): string | undefined {
  if (!eType) return undefined;
  const proxyURI = (eType as { eProxyURI?: () => { toString(): string } | null }).eProxyURI?.();
  if (proxyURI) return proxyURI.toString();
  const classifier = eType as {
    getEPackage?: () => { getNsURI?: () => string | undefined } | null;
    getName?: () => string | undefined;
  };
  const nsURI = classifier.getEPackage?.()?.getNsURI?.();
  const name = classifier.getName?.();
  if (!name) return undefined;
  return nsURI ? `${nsURI}#//${name}` : name;
}

/**
 * Parameters in declaration order. `index` is what the catalog orders
 * by; a parameter without one keeps the position it was read in, which
 * is the same order for a document the broker wrote.
 */
function sortedParameters(operation: ServiceOperation): Parameter[] {
  return toArray<Parameter>(operation.parameters)
    .map((parameter, at) => ({ parameter, at }))
    .sort((left, right) => {
      const leftIndex = Number(left.parameter.index ?? left.at);
      const rightIndex = Number(right.parameter.index ?? right.at);
      return (Number.isFinite(leftIndex) ? leftIndex : left.at) - (Number.isFinite(rightIndex) ? rightIndex : right.at);
    })
    .map(entry => entry.parameter);
}

function parameterDocs(operation: ServiceOperation): string[] {
  return sortedParameters(operation)
    .filter(parameter => (parameter.description ?? '') !== '')
    .map(parameter => `@param ${identifier(parameter.name, 'arg')} ${parameter.description}`);
}

function assign(target: string, feature: string, value: unknown): string[] {
  const text = value === undefined || value === null ? '' : String(value);
  return text === '' ? [] : [`  ${target}.${feature} = ${quote(text)};`];
}

/** `null` drops a segment; `''` is a blank line the reader wants. */
function render(segments: Array<string | null>): string {
  return segments.filter((segment): segment is string => segment !== null).join('\n') + '\n';
}

function docOrNull(description: string | undefined, indent: string, extra: string[] = []): string | null {
  const text = doc(description, indent, extra);
  return text === '' ? null : text.replace(/\n$/, '');
}

function doc(description: string | undefined, indent: string, extra: string[] = []): string {
  const text = (description ?? '').trim();
  if (text === '' && extra.length === 0) return '';
  const lines = [...(text === '' ? [] : wrap(text, 68)), ...extra];
  return `${indent}/**\n${lines.map(line => `${indent} * ${line}`).join('\n')}\n${indent} */\n`;
}

function wrap(text: string, width: number): string[] {
  const lines: string[] = [];
  let line = '';
  for (const word of text.split(/\s+/)) {
    if (line !== '' && line.length + word.length + 1 > width) {
      lines.push(line);
      line = word;
    } else {
      line = line === '' ? word : `${line} ${word}`;
    }
  }
  if (line !== '') lines.push(line);
  return lines;
}

function quote(text: string): string {
  return `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n')}'`;
}
