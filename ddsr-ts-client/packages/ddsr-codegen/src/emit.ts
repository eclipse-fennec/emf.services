import { fingerprint, toArray } from '@ddsr/client';
import type { Parameter, ServiceInterface, ServiceOperation } from '@ddsr/model';
import { identifier, mapType } from './type-mapping.js';

export interface GeneratedFile {
  path: string;
  content: string;
}

const HEADER = `/*
 * Generated by @ddsr/codegen from a DDSR service catalog.
 * DO NOT EDIT - regenerate instead.
 */
`;

/**
 * The consumer's side of a contract: the interface to call, the name to
 * look it up under, and the fingerprint the catalog carried when this
 * was generated.
 *
 * The fingerprint is the reason this is worth generating rather than
 * writing by hand. Passed to find(), the broker returns only
 * implementations whose contract hashes to exactly it — so a provider
 * that has since changed its operations is not silently called with the
 * signature this file believes in. A handwritten stub cannot know that
 * number.
 */
export function emitConsumer(serviceInterface: ServiceInterface): GeneratedFile {
  const name = identifier(serviceInterface.name, 'Service');
  const operations = toArray<ServiceOperation>(serviceInterface.operations);
  const imports = new Set<string>();

  const methods = operations.map(operation => {
    const method = identifier(operation.name, 'operation');
    const returned = mapType(operation.returnType);
    if (returned.modelImport) imports.add(returned.modelImport);

    const parameters = sortedParameters(operation).map(parameter => {
      const mapped = mapType(parameter.type);
      if (mapped.modelImport) imports.add(mapped.modelImport);
      const optional = parameter.optional === true ? '?' : '';
      return `${identifier(parameter.name, 'arg')}${optional}: ${mapped.text}`;
    });

    return `${doc(operation.description, '  ', parameterDocs(operation))}  ${method}(${parameters.join(', ')}): Promise<${returned.text === 'void' ? 'void' : returned.text}>;`;
  });

  const sd1 = fingerprint(serviceInterface);
  const body: Array<string | null> = [
    HEADER,
    imports.size > 0 ? `import type { ${[...imports].sort().join(', ')} } from '@ddsr/model';` : null,
    `import type { DdsrConsumer } from '@ddsr/client';`,
    ``,
    docOrNull(serviceInterface.description, ''),
    `export interface ${name} {`,
    methods.join('\n\n'),
    `}`,
    ``,
    `/** The ServiceInterface.name this contract is registered under. */`,
    `export const ${name}InterfaceName = ${quote(serviceInterface.name ?? name)};`,
    ``,
    `/** The version the catalog carried when this file was generated. */`,
    `export const ${name}Version = ${quote(serviceInterface.version ?? '')};`,
    ``,
    `/**`,
    ` * The sd1 fingerprint of the contract above. Pass it to find() and`,
    ` * the broker answers only with implementations whose description`,
    ` * hashes to exactly this - compatibility by identity, so a provider`,
    ` * that changed its operations is not called with these signatures.`,
    ` */`,
    `export const ${name}Fingerprint = ${quote(sd1 ?? '')};`,
    ``,
    `/**`,
    ` * Resolve one, contract-addressed. Returns undefined when the broker`,
    ` * knows no implementation of exactly this contract.`,
    ` */`,
    `export async function get${name}(`,
    `  consumer: DdsrConsumer,`,
    `  filter?: string`,
    `): Promise<${name} | undefined> {`,
    `  const locator = await consumer.findOne(${name}InterfaceName, filter, ${name}Fingerprint);`,
    `  if (!locator) return undefined;`,
    `  return consumer.getService<${name}>(${name}InterfaceName, filter);`,
    `}`,
    ``,
  ];
  return { path: `src/${name}.ts`, content: render(body) };
}

/**
 * The provider's side: what an implementation has to offer, and the
 * contract as a model object to publish it with.
 *
 * The second part is what makes this more than a convenience. A
 * provider has to hand the broker a ServiceInterface built feature by
 * feature - the example does it in 154 lines for two operations - and
 * every detail that drifts from the catalog changes the fingerprint,
 * which means consumers stop finding the service. Generated from the
 * catalog, it cannot drift.
 */
export function emitProvider(serviceInterface: ServiceInterface): GeneratedFile {
  const name = identifier(serviceInterface.name, 'Service');
  const operations = toArray<ServiceOperation>(serviceInterface.operations);
  const imports = new Set<string>();

  const methods = operations.map(operation => {
    const method = identifier(operation.name, 'operation');
    const returned = mapType(operation.returnType);
    if (returned.modelImport) imports.add(returned.modelImport);
    const parameters = sortedParameters(operation).map(parameter => {
      const mapped = mapType(parameter.type);
      if (mapped.modelImport) imports.add(mapped.modelImport);
      return `${identifier(parameter.name, 'arg')}${parameter.optional === true ? '?' : ''}: ${mapped.text}`;
    });
    const result = returned.text === 'void' ? 'void | Promise<void>' : `${returned.text} | Promise<${returned.text}>`;
    return `${doc(operation.description, '  ', parameterDocs(operation))}  ${method}(${parameters.join(', ')}): ${result};`;
  });

  const body: Array<string | null> = [
    HEADER,
    `import { DDSRFactory } from '@ddsr/model';`,
    `import type { ${[...new Set([...imports, 'ServiceInterface'])].sort().join(', ')} } from '@ddsr/model';`,
    ``,
    docOrNull(serviceInterface.description, '', [`The implementation side of ${serviceInterface.name ?? name}. Every operation`, 'the catalog declares has to be here; a return value may be a', 'promise or not.']),
    `export interface ${name}Implementation {`,
    methods.join('\n\n'),
    `}`,
    ``,
    `/** The operation names, for wiring a transport that dispatches by name. */`,
    `export const ${name}OperationNames = [${operations.map(o => quote(o.name ?? '')).join(', ')}] as const;`,
    ``,
    `/**`,
    ` * The contract as a model object, exactly as the catalog has it.`,
    ` * This is what publish() needs, and what the fingerprint is computed`,
    ` * over - so it is generated rather than typed out.`,
    ` */`,
    `export function build${name}Interface(): ServiceInterface {`,
    `  const factory = DDSRFactory.eINSTANCE;`,
    `  const serviceInterface = factory.createServiceInterface();`,
    ...assign('serviceInterface', 'name', serviceInterface.name),
    ...assign('serviceInterface', 'version', serviceInterface.version),
    ...assign('serviceInterface', 'description', serviceInterface.description),
    ...operations.flatMap((operation, index) => buildOperation(operation, index)),
    `  return serviceInterface;`,
    `}`,
    ``,
  ];
  return { path: `src/${name}Provider.ts`, content: render(body) };
}

function buildOperation(operation: ServiceOperation, index: number): string[] {
  const local = `operation${index}`;
  const lines = [
    ``,
    `  const ${local} = factory.createServiceOperation();`,
    ...assign(local, 'name', operation.name),
    ...assign(local, 'returnType', operation.returnType),
    ...assign(local, 'description', operation.description),
  ];
  for (const [at, parameter] of sortedParameters(operation).entries()) {
    const parameterLocal = `${local}Parameter${at}`;
    lines.push(
      `  const ${parameterLocal} = factory.createParameter();`,
      ...assign(parameterLocal, 'name', parameter.name),
      ...assign(parameterLocal, 'type', parameter.type),
      ...assign(parameterLocal, 'description', parameter.description),
      ...(at > 0 ? [`  ${parameterLocal}.index = ${at};`] : []),
      ...(parameter.optional === true ? [`  ${parameterLocal}.optional = true;`] : []),
      ...assign(parameterLocal, 'defaultValue', parameter.defaultValue),
      `  ${local}.parameters.push(${parameterLocal});`,
    );
  }
  lines.push(`  serviceInterface.operations.push(${local});`);
  return lines;
}

/**
 * Parameters in declaration order. `index` is what the catalog orders
 * by; a parameter without one keeps the position it was read in, which
 * is the same order for a document the broker wrote.
 */
function sortedParameters(operation: ServiceOperation): Parameter[] {
  return toArray<Parameter>(operation.parameters)
    .map((parameter, at) => ({ parameter, at }))
    .sort((left, right) => {
      const leftIndex = Number(left.parameter.index ?? left.at);
      const rightIndex = Number(right.parameter.index ?? right.at);
      return (Number.isFinite(leftIndex) ? leftIndex : left.at) - (Number.isFinite(rightIndex) ? rightIndex : right.at);
    })
    .map(entry => entry.parameter);
}

function parameterDocs(operation: ServiceOperation): string[] {
  return sortedParameters(operation)
    .filter(parameter => (parameter.description ?? '') !== '')
    .map(parameter => `@param ${identifier(parameter.name, 'arg')} ${parameter.description}`);
}

function assign(target: string, feature: string, value: unknown): string[] {
  const text = value === undefined || value === null ? '' : String(value);
  return text === '' ? [] : [`  ${target}.${feature} = ${quote(text)};`];
}

/** `null` drops a segment; `''` is a blank line the reader wants. */
function render(segments: Array<string | null>): string {
  return segments.filter((segment): segment is string => segment !== null).join('\n') + '\n';
}

function docOrNull(description: string | undefined, indent: string, extra: string[] = []): string | null {
  const text = doc(description, indent, extra);
  return text === '' ? null : text.replace(/\n$/, '');
}

function doc(description: string | undefined, indent: string, extra: string[] = []): string {
  const text = (description ?? '').trim();
  if (text === '' && extra.length === 0) return '';
  const lines = [...(text === '' ? [] : wrap(text, 68)), ...extra];
  return `${indent}/**\n${lines.map(line => `${indent} * ${line}`).join('\n')}\n${indent} */\n`;
}

function wrap(text: string, width: number): string[] {
  const lines: string[] = [];
  let line = '';
  for (const word of text.split(/\s+/)) {
    if (line !== '' && line.length + word.length + 1 > width) {
      lines.push(line);
      line = word;
    } else {
      line = line === '' ? word : `${line} ${word}`;
    }
  }
  if (line !== '') lines.push(line);
  return lines;
}

function quote(text: string): string {
  return `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n')}'`;
}
